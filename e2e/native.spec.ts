import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

test('native ElseMesh renders current world and persists sky and drifting mist controls', async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const out = path.resolve('../../outputs');
  mkdirSync(out, { recursive: true });
  await page.goto('/');
  await page.getByTitle('Assets').click();
  await page.getByRole('button', { name: /Building block/ }).click();
  await page.getByRole('button', { name: 'ElseMesh graphics' }).click();
  const frame = page.frameLocator('iframe[title="ElseMesh native WebGPU preview"]');
  await expect(frame.locator('#status')).toContainText('drag to look', { timeout: 45000 });
  const native = page.frames().find(f => f.url().includes('native-preview.html'))!;
  await expect.poll(() => native.evaluate(() => (window as unknown as { __nativePreview?: { frames: number } }).__nativePreview?.frames ?? 0)).toBeGreaterThan(30);
  await page.waitForTimeout(2500);
  await page.screenshot({ path: path.join(out, 'elsemesh-native-day.png') });
  const set = async (label: string, value: string) => { await page.getByRole('slider', { name: label, exact: true }).fill(value); };
  await set('Time of day', '1.5');
  await page.waitForTimeout(2500);
  await page.screenshot({ path: path.join(out, 'elsemesh-native-night.png') });
  await set('Time of day', '6.3'); await set('Cloud coverage', '0');
  await set('Drifting mist', '0.035'); await set('Mist wind speed', '8'); await set('Mist vertical reach', '16');
  await page.waitForTimeout(2500);
  await page.screenshot({ path: path.join(out, 'elsemesh-native-mist-a.png') });
  const first = await native.evaluate(() => (window as unknown as { __nativePreview: { time: number } }).__nativePreview.time);
  await page.waitForTimeout(3000);
  await page.screenshot({ path: path.join(out, 'elsemesh-native-mist-b.png') });
  const state = await native.evaluate(() => (window as unknown as { __nativePreview: { time: number; objects: number; settings: unknown } }).__nativePreview);
  expect(state.time).toBeGreaterThan(first + 2);
  expect(state.objects).toBe(1);
  await page.getByRole('button', { name: 'Back to editor ×' }).click();
  await expect(page.getByRole('button', { name: 'Enter preview' })).toBeVisible();
  await expect(page.locator('.topbar .save-state')).toContainText(/^Saved /);
  await page.reload();
  await page.getByRole('button', { name: 'ElseMesh graphics' }).click();
  await expect(page.getByRole('slider', { name: 'Time of day', exact: true })).toHaveValue('6.3');
  await expect(page.getByRole('slider', { name: 'Drifting mist', exact: true })).toHaveValue('0.035');
  writeFileSync(path.join(out, 'elsemesh-native-evidence.json'), JSON.stringify({ errors, firstMistTime: first, state }, null, 2));
  expect(errors).toEqual([]);
});
