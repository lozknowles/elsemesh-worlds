import { expect, test } from '@playwright/test';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

test.use({ headless: false });
type State = { frames: number; time: number; camera: number[]; navigation: { clearance: number; speed: number; speedMultiplier: number; collisions: number; blocked: boolean; mode: string; keys: string[]; yaw: number; pitch: number } };
const distance = (a: number[], b: number[]) => Math.hypot(...a.map((value, i) => value - b[i]!));
test('Hope native navigation zooms into terrain safely, reverses, travels, resets and leaves editor project intact', async ({ page }) => {
  test.setTimeout(180000);
  const errors: string[] = []; page.on('pageerror', error => { errors.push(error.message); console.log('NAV pageerror: ' + error.message); }); page.on('console', message => { if (message.type() === 'error') { errors.push(message.text()); console.log('NAV error: ' + message.text()); } });
  const file = path.resolve('../../outputs/hope-valley-lightweight.emw'), original = JSON.parse(readFileSync(file, 'utf8'));
  await page.goto('/'); await page.bringToFront();
  await page.locator('input[type=file][accept*=".emw"]').setInputFiles(file); await expect(page.getByText('Project opened', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'ElseMesh graphics' }).click();
  console.log('NAV native iframe opened');
  const frameLocator = page.frameLocator('iframe[title="ElseMesh native WebGPU preview"]');
  await expect(frameLocator.locator('#status')).toContainText('wheel zoom', { timeout: 60000 });
  const native = page.frames().find(frame => frame.url().includes('native-preview.html'))!;
  const read = () => native.evaluate(() => (window as unknown as { __nativePreview: State }).__nativePreview);
  await expect.poll(async () => (await read())?.frames ?? 0, { timeout: 45000 }).toBeGreaterThan(5);
  console.log('NAV native rendered >5 frames');
  await page.getByRole('button', { name: 'Hide controls', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Overview', exact: true })).toBeVisible();
  const overview = await read();
  const canvas = frameLocator.locator('canvas'); await canvas.hover({ position: { x: 500, y: 250 } });
  await page.mouse.wheel(0, -1000);
  console.log('NAV wheel input ' + JSON.stringify((await read()).navigation));
  await expect.poll(async () => (await read()).navigation.clearance, { timeout: 15000 }).toBeLessThan(overview.navigation.clearance - 80);
  console.log('NAV wheel descent ' + JSON.stringify((await read()).navigation));
  await expect.poll(async () => (await read()).navigation.collisions, { timeout: 15000 }).toBeGreaterThan(0);
  const close = await read(); expect(close.navigation.clearance).toBeGreaterThanOrEqual(2.1999);
  console.log('NAV wheel collision checked');
  const out = path.resolve('../../outputs'); mkdirSync(out, { recursive: true });
  await page.screenshot({ path: path.join(out, 'hope-navigation-wheel-close.png') });
  await page.mouse.wheel(0, 400);
  await expect.poll(async () => distance((await read()).camera, close.camera), { timeout: 12000 }).toBeGreaterThan(10);
  const reverse = await read(); expect(reverse.navigation.clearance).toBeGreaterThan(close.navigation.clearance);
  await page.getByRole('button', { name: 'Return to spawn', exact: true }).click();
  await expect.poll(async () => (await read()).navigation.mode).toBe('spawn');
  const spawn = await read(); expect(spawn.camera[0]).toBeCloseTo(original.spawn.position[0]); expect(spawn.camera[2]).toBeCloseTo(original.spawn.position[2]); expect(spawn.navigation.clearance).toBeGreaterThanOrEqual(2.2);
  await page.keyboard.down('w'); await expect.poll(async () => (await read()).navigation.collisions, { timeout: 12000 }).toBeGreaterThan(spawn.navigation.collisions); await page.keyboard.up('w');
  const blocked = await read(); expect(blocked.navigation.clearance).toBeGreaterThanOrEqual(2.1999);
  await page.keyboard.down('s'); await expect.poll(async () => distance((await read()).camera, blocked.camera), { timeout: 10000 }).toBeGreaterThan(2); await page.keyboard.up('s');
  await page.getByRole('button', { name: 'Recenter', exact: true }).click();
  await page.getByLabel('Flying speed multiplier', { exact: true }).selectOption('8');
  await expect.poll(async () => (await read()).navigation.speedMultiplier).toBe(8);
  await canvas.click({ position: { x: 500, y: 250 } });
  const travelStart = await read(), wallStart = Date.now();
  await page.keyboard.down('Shift'); await page.keyboard.down('s');
  await expect.poll(async () => distance((await read()).camera, travelStart.camera), { timeout: 20000, intervals: [200, 300, 500] }).toBeGreaterThan(2000);
  await page.keyboard.up('s'); await page.keyboard.up('Shift');
  const travelEnd = await read(), wallTravelMs = Date.now() - wallStart;
  console.log('NAV >2km travel checked in ' + wallTravelMs + 'ms');
  await page.getByRole('button', { name: 'Overview', exact: true }).click(); await expect.poll(async () => (await read()).navigation.mode).toBe('overview');
  const reset = await read(); expect(distance(reset.camera, overview.camera)).toBeLessThan(.01); expect(reset.navigation.keys).toEqual([]); expect(reset.navigation.speed).toBe(0);
  await native.evaluate(() => window.postMessage({ type: 'elsemesh-native-navigation', action: 'spawn' }, location.origin));
  await page.waitForTimeout(200); expect((await read()).navigation.mode).toBe('overview');
  await page.screenshot({ path: path.join(out, 'hope-navigation-overview.png') });
  await page.getByRole('button', { name: 'Back to editor ×', exact: true }).click();
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Save project', exact: true }).click()]);
  expect(JSON.parse(readFileSync((await download.path())!, 'utf8'))).toEqual(original);
  await page.getByRole('button', { name: 'ElseMesh graphics' }).click();
  await expect(frameLocator.locator('#status')).toContainText('wheel zoom', { timeout: 60000 });
  const reentered = page.frames().find(frame => frame.url().includes('native-preview.html'))!;
  await expect.poll(async () => reentered.evaluate(() => (window as unknown as { __nativePreview?: State }).__nativePreview?.navigation.mode), { timeout: 30000 }).toBe('overview');
  writeFileSync(path.join(out, 'hope-navigation-evidence.json'), JSON.stringify({ errors, objectCount: original.objects.length, overview, close, reverse, spawn, blocked, travelStart, travelEnd, travelledMetres: distance(travelEnd.camera, travelStart.camera), wallTravelMs, reset, qualification: 'Actual Hope Valley 60-tree scene; native UI interaction and terrain clearance. Does not imply collisions with buildings or trees.' }, null, 2));
  expect(errors).toEqual([]);
});
